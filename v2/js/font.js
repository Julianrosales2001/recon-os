  function parse(table) {
    const out = {};
    Object.keys(table).forEach(k => {
      out[k] = table[k].split(',').map(row => {
        const bits = [];
        for (let i = 0; i < row.length; i++) bits.push(row.charCodeAt(i) === 49);
        return bits;
      });
    });
    return out;
  }

