    // Width in dots of a string in a given face at a given scale.
    measure(str, face, scale) {
      const f = face === 'mini' ? this.mini : this.std;
      const n = [...norm(str)].length;
      if (!n) return 0;
      return (n * f.adv - (f.adv - f.w)) * (scale || 1);
    },
    // Truncate to fit maxDots, adding an ellipsis-dot if cut.
    fit(str, maxDots, face, scale) {
      const f = face === 'mini' ? this.mini : this.std;
      const chars = [...norm(str)];
      const maxChars = Math.floor((maxDots / (scale || 1) + (f.adv - f.w)) / f.adv);
      if (chars.length <= maxChars) return chars.join('');
      return chars.slice(0, Math.max(0, maxChars - 1)).join('') + (face === 'mini' ? '.' : '·');
    }
