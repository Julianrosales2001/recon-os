  const SUBS = { '–': '-', '—': '-', '‘': "'", '’': "'", '“': '"', '”': '"', '…': '...', '{': '(', '}': ')',
    '`': "'", '■': '■', '▶': '▸', '◀': '◂', '►': '▸', '◄': '◂', '⚠': '!', '\t': ' ' };
  function norm(str) {
    if (str == null) return '';
    let s = String(str);
    try { s = s.normalize('NFD').replace(/[̀-ͯ]/g, ''); } catch (e) {}
    s = s.toUpperCase();
    let out = '';
    for (const ch of s) out += (SUBS[ch] !== undefined ? SUBS[ch] : ch);
    return out;
  }

